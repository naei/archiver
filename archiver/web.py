"""Main content of web pages (text, structure, images), without the site's design."""
import copy
import html
import re
from datetime import datetime
from email.utils import parsedate_to_datetime
from urllib.parse import urljoin, urlparse

import trafilatura
from lxml import etree

MAX_IMAGES = 40
FEED_PATHS = ("/feed", "/rss", "/feed.xml", "/rss.xml", "/atom.xml", "/index.xml")
FEED_TYPES = ("application/rss+xml", "application/atom+xml", "application/rdf+xml", "application/xml", "text/xml")
# Parts of a page that are not its content: what sites hide when printing, navigation, and MediaWiki's
# editing links, link boxes and maintenance notes.
NOISE_CLASSES = ("noprint", "mw-editsection", "navbox", "navbox-styles", "mw-jump-link", "mw-cite-backlink",
                 "sistersitebox", "side-box", "ambox", "hatnote", "printfooter", "catlinks")
NOISE = "//*[@role='navigation' or " + " or ".join(
    f"contains(concat(' ', normalize-space(@class), ' '), ' {name} ')" for name in NOISE_CLASSES) + "]"
BACKLINKS = ("^", "↑", "↩", "↩︎", "⏎")
ATOM = "{http://www.w3.org/2005/Atom}"
CONTENT = "{http://purl.org/rss/1.0/modules/content/}encoded"
CREATOR = "{http://purl.org/dc/elements/1.1/}creator"
MEDIA = "{http://search.yahoo.com/mrss/}"


class NoContent(ValueError):
    """No main content could be extracted from the page."""
BLOCKS = ("head", "p", "quote", "item", "code", "row")
INLINE = {"#b": "strong", "#i": "em", "#u": "u", "#t": "code", "#sub": "sub", "#sup": "sup"}


def absolute(src, base):
    if not src:
        return None
    url = urljoin(base, src.strip())
    return url if urlparse(url).scheme in ("http", "https") else None


def clean(page):
    """The page's tree without what is not its content and would be taken for it: editing links, boxes of
    navigation links, and links to a place in the page itself, which lead nowhere in an archive."""
    tree = trafilatura.load_html(page)
    if tree is None:
        return None
    for element in tree.xpath(NOISE):
        if element.getparent() is not None:
            element.drop_tree()
    for link in tree.xpath("//a[starts-with(@href, '#')]"):
        # A footnote mark stays as text; the arrow back from a footnote to the text goes.
        if (link.text_content() or "").strip() in BACKLINKS:
            link.drop_tree()
        else:
            del link.attrib["href"]
    return tree


def extract(page, url, recall=False):
    """Metadata and main content of an HTML page, as trafilatura's XML tree."""
    tree = clean(page)
    if tree is None:
        raise NoContent("No main content was found on this page. "
                        "It may be empty, for subscribers only or generated by JavaScript.")
    # Each reading gets its own copy: both change the tree they are given.
    page = copy.deepcopy(tree)
    metadata = trafilatura.extract_metadata(copy.deepcopy(tree), default_url=url)
    xml = trafilatura.extract(
        page, url=url, output_format="xml", include_images=True, include_links=True,
        include_formatting=True, include_tables=True, include_comments=False, favor_recall=recall,
    )
    main = etree.fromstring(xml.encode()).find("main") if xml else None
    if main is None or not "".join(main.itertext()).strip():
        raise NoContent("No main content was found on this page. "
                        "It may be empty, for subscribers only or generated by JavaScript.")
    images = []
    for graphic in main.iter("graphic"):
        source = absolute(graphic.get("src"), url)
        if source and source not in images:
            images.append(source)
    field = lambda name: (getattr(metadata, name, None) or None) if metadata else None
    title = field("title")
    heading = main.find(".//head")
    if title and heading is not None:
        # "Article — Site name" page titles: keep the article's own heading.
        short = " ".join(plain(heading).split())
        if short and re.fullmatch(re.escape(short) + r"\s*[—–\-|·:]\s*\S.*", title):
            title = short
    return {
        "title": title, "author": field("author"), "date": field("date"),
        "site": field("sitename") or urlparse(url).hostname, "summary": field("description"),
        "cover": absolute(field("image"), url), "url": absolute(field("url"), url) or url,
        "main": main, "images": images[:MAX_IMAGES],
    }


def feed_candidates(url):
    """Usual feed addresses for the site of `url`, including a first-level section such as /blog."""
    parsed = urlparse(url)
    root = f"{parsed.scheme}://{parsed.netloc}"
    section = parsed.path.strip("/").split("/")[0] if parsed.path.count("/") > 1 else ""
    return [root + path for path in FEED_PATHS] + ([f"{root}/{section}/feed", f"{root}/{section}/index.xml"] if section else [])


def page_key(url):
    parsed = urlparse(url.strip())
    return (parsed.hostname or "").removeprefix("www.") + parsed.path.rstrip("/")


def feed_date(value):
    if not value:
        return None
    try:
        return parsedate_to_datetime(value).date().isoformat()
    except (TypeError, ValueError):
        pass
    try:
        return datetime.fromisoformat(value.strip().replace("Z", "+00:00")).date().isoformat()
    except ValueError:
        return None


def feed_entry(feed, url):
    """The entry for `url` in an RSS or Atom feed, or None."""
    try:
        # No DTD, entities or network access: feeds are untrusted XML.
        root = etree.fromstring(feed, etree.XMLParser(resolve_entities=False, no_network=True, load_dtd=False))
    except (etree.XMLSyntaxError, ValueError):
        return None
    site = root.findtext("channel/title") or root.findtext(f"{ATOM}title")
    for entry in [*root.iter("item"), *root.iter(f"{ATOM}entry")]:
        links = [entry.findtext("link"), entry.findtext("guid"), entry.findtext(f"{ATOM}id")]
        links += [link.get("href") for link in entry.findall(f"{ATOM}link")]
        if not any(link and page_key(link) == page_key(url) for link in links):
            continue
        content = entry.find(CONTENT)
        if content is None:
            content = entry.find(f"{ATOM}content")
        if content is not None and content.get("type") == "xhtml":
            body = "".join(etree.tostring(child, encoding="unicode") for child in content)
        else:
            body = content.text if content is not None else None
        summary = entry.findtext("description") or entry.findtext(f"{ATOM}summary")
        cover = next((media.get("url") for media in entry.iter(f"{MEDIA}content", f"{MEDIA}thumbnail", "enclosure")
                      if media.get("url") and (media.get("medium") == "image" or (media.get("type") or "image/").startswith("image/"))), None)
        return {
            "title": (entry.findtext("title") or entry.findtext(f"{ATOM}title") or "").strip() or None,
            "author": entry.findtext(CREATOR) or entry.findtext(f"{ATOM}author/{ATOM}name") or None,
            "date": feed_date(entry.findtext("pubDate") or entry.findtext(f"{ATOM}published") or entry.findtext(f"{ATOM}updated")),
            "site": (site or "").strip() or None, "content": body or summary or "", "complete": bool(body),
            "cover": absolute(cover, url),
        }
    return None


def from_feed(entry, url):
    """The article for `url` built from its feed entry, with the same shape as `extract`."""
    page = (f"<html><head><title>{html.escape(entry['title'] or '')}</title></head>"
            f"<body><article>{entry['content']}</article></body></html>")
    article = extract(page.encode(), url, recall=True)
    article.update({key: entry[key] or article[key] for key in ("title", "author", "date", "site", "cover")})
    article["url"] = url
    return article


def plain(element):
    parts = [element.text or ""]
    for child in element:
        parts.append("\n" if child.tag == "lb" else plain(child))
        parts.append(child.tail or "")
    return "".join(parts)


def text(main):
    """Readable plain text, one paragraph per block."""
    blocks = []
    for element in main.iter(*BLOCKS):
        if any(ancestor.tag in BLOCKS for ancestor in element.iterancestors()):
            continue
        content = re.sub(r"[ \t]+", " ", plain(element)).strip()
        if element.tag == "row":
            content = " | ".join(" ".join(plain(cell).split()) for cell in element)
        if content:
            blocks.append(("• " if element.tag == "item" else "") + content)
    return "\n\n".join(blocks)


def render(main, base, images, title):
    """Safe HTML for the article. Only a fixed set of tags is produced and every
    string is escaped; `images` maps an image's source URL to its local URL."""
    escape = lambda value: html.escape(value or "", quote=True)
    same = lambda value: " ".join(value.split()).casefold() == " ".join((title or "").split()).casefold()
    title_shown = [False]

    def children(element, block):
        parts = [escape(element.text)]
        for child in element:
            parts.append(node(child, block))
            parts.append(escape(child.tail))
        return "".join(parts)

    def node(element, block):
        tag, rend = element.tag, element.get("rend") or ""
        if tag == "head":
            if not title_shown[0] and same(plain(element)):
                title_shown[0] = True
                return ""  # the title is already shown above the article
            level = min(max(int(rend[1]) if re.fullmatch(r"h[1-6]", rend) else 2, 2), 4)
            return f"<h{level}>{children(element, False)}</h{level}>"
        if tag == "p":
            return f"<p>{children(element, False)}</p>"
        if tag == "quote":
            return f"<blockquote>{children(element, True)}</blockquote>"
        if tag == "list":
            kind = "ol" if rend == "ol" else "ul"
            return f"<{kind}>{children(element, True)}</{kind}>"
        if tag == "item":
            return f"<li>{children(element, True)}</li>"
        if tag == "lb":
            return "<br>"
        if tag == "hi":
            inline = INLINE.get(rend)
            content = children(element, False)
            return f"<{inline}>{content}</{inline}>" if inline else content
        if tag == "del":
            return f"<s>{children(element, False)}</s>"
        if tag == "ref":
            target = absolute(element.get("target"), base)
            content = children(element, False)
            return f'<a href="{escape(target)}" target="_blank" rel="noopener noreferrer">{content}</a>' if target else content
        if tag == "graphic":
            local = images.get(absolute(element.get("src"), base))
            return f'<img src="{escape(local)}" alt="{escape(element.get("alt"))}" loading="lazy">' if local else ""
        if tag == "code":
            content = escape(plain(element))
            return f"<pre><code>{content}</code></pre>" if block else f"<code>{content}</code>"
        if tag == "table":
            return f"<div class=\"table-wrap\"><table>{children(element, False)}</table></div>"
        if tag == "row":
            return f"<tr>{children(element, False)}</tr>"
        if tag == "cell":
            cell = "th" if element.get("role") == "head" else "td"
            return f"<{cell}>{children(element, True)}</{cell}>"
        return children(element, block)

    return children(main, True).strip()
